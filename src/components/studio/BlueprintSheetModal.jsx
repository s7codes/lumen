import { useCallback, useId, useMemo, useRef } from 'react';
import { useToast } from '../../contexts/ToastContext.jsx';
import { useModalDialog } from '../../hooks/useModalDialog.js';
import {
  blueprintFilename,
  buildBlueprintSvg,
  buildBlueprintSvgMarkup,
  compileBlueprintSheet,
  SVG_MIME,
} from '../../lib/blueprint-sheet.js';
import { buildBlueprintDxf, DXF_LAYERS, DXF_MIME } from '../../lib/dxf-export.js';
import { downloadText } from '../../lib/download.js';

function localDateIso() {
  const now = new Date();
  const pad = (v) => String(v).padStart(2, '0');
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

/**
 * Issued drawing for the current wall: a 1:20 A3 elevation with the drilling
 * schedule and an ISO 7200 title block, downloadable as SVG or R12 DXF.
 */
export function BlueprintSheetModal({ open, onClose, layout, projectName, returnFocus }) {
  const panelRef = useRef(null);
  const closeRef = useRef(null);
  const previewRef = useRef(null);
  const uid = useId();
  const { addToast } = useToast();

  useModalDialog({ open, panelRef, initialFocusRef: closeRef, returnFocus, onClose });

  const sheet = useMemo(
    () => (open ? compileBlueprintSheet(layout, { projectName, dateIso: localDateIso() }) : null),
    [open, layout, projectName],
  );
  // Inline markup is generated by buildBlueprintSvg: fixed element set, numeric
  // attributes and XML-escaped text only, so no input reaches the DOM unescaped.
  const markup = useMemo(() => (sheet ? { __html: buildBlueprintSvgMarkup(sheet) } : null), [sheet]);

  // Row hover marks the matching crosshair by direct attribute writes, no re-render.
  const highlight = useCallback((anchorId) => {
    const root = previewRef.current;
    if (!root) return;
    root.querySelector('[data-anchor][data-active]')?.removeAttribute('data-active');
    if (anchorId) root.querySelector(`[data-anchor="${CSS.escape(anchorId)}"]`)?.setAttribute('data-active', '');
  }, []);

  if (!open || !sheet) return null;

  const t = sheet.titleBlock;
  const plural = (count, word) => `${count} ${count === 1 ? word : `${word}s`}`;

  const downloadSvg = () => {
    const filename = blueprintFilename(t.projectName, 'svg');
    downloadText(filename, buildBlueprintSvg(sheet), SVG_MIME);
    addToast(`Blueprint saved as ${filename}. ${plural(t.anchorCount, 'anchor')} at ${t.scale}.`, 'success');
  };

  const downloadDxf = () => {
    const filename = blueprintFilename(t.projectName, 'dxf');
    downloadText(filename, buildBlueprintDxf(sheet), DXF_MIME);
    addToast(`AutoCAD drawing saved as ${filename}. R12 DXF, ${DXF_LAYERS.length} layers, units cm.`, 'success');
  };

  return (
    <div className="modal-root">
      <div className="modal-scrim" onClick={onClose} aria-hidden="true" />
      <div
        ref={panelRef}
        className="blueprint-modal optical"
        role="dialog"
        aria-modal="true"
        aria-label="Architectural blueprint sheet"
        aria-describedby={`${uid}-meta`}
        data-testid="blueprint-sheet-modal"
      >
        <header className="blueprint-modal__header">
          <div>
            <p className="index-label">
              <span className="index-label__num">04</span> / Blueprint
            </p>
            <h2 className="blueprint-modal__title">{t.projectName}</h2>
            <p id={`${uid}-meta`} className="blueprint-modal__meta mono">
              {t.drawingNumber} / Rev {t.revision} / {t.scale} / {t.paper} / {t.dateIso}
            </p>
          </div>
          <button ref={closeRef} type="button" className="drawer__close" onClick={onClose}>
            Close
          </button>
        </header>

        <div className="blueprint-modal__body">
          <section className="blueprint-card blueprint-card--sheet" aria-label="Sheet preview">
            <div
              ref={previewRef}
              className="blueprint-card__canvas"
              data-testid="blueprint-sheet-svg"
              data-anchors={t.anchorCount}
              data-modules={t.moduleCount}
              dangerouslySetInnerHTML={markup}
            />
          </section>

          <aside className="blueprint-card blueprint-card--spec" aria-label="Title block">
            <dl className="blueprint-spec" data-testid="blueprint-title-block">
              <div className="blueprint-spec__row blueprint-spec__row--wide">
                <dt>Issued by</dt>
                <dd>
                  {t.issuer}
                  <span className="blueprint-spec__sub">{t.address}</span>
                </dd>
              </div>
              <div className="blueprint-spec__row blueprint-spec__row--wide">
                <dt>Project</dt>
                <dd data-testid="blueprint-project-name">{t.projectName}</dd>
              </div>
              <div className="blueprint-spec__row">
                <dt>Drawing</dt>
                <dd>{t.drawingNumber}</dd>
              </div>
              <div className="blueprint-spec__row">
                <dt>Scale</dt>
                <dd data-testid="blueprint-scale">{t.scale}</dd>
              </div>
              <div className="blueprint-spec__row">
                <dt>Modules</dt>
                <dd>{t.moduleCount}</dd>
              </div>
              <div className="blueprint-spec__row">
                <dt>Anchors</dt>
                <dd>{t.anchorCount}</dd>
              </div>
              <div className="blueprint-spec__row">
                <dt>24V load</dt>
                <dd>{t.loadW} W</dd>
              </div>
              {t.dimmed > 0 && (
                <div className="blueprint-spec__row">
                  <dt>DALI-2 scene</dt>
                  <dd data-testid="blueprint-scene-draw">{t.activeW} W</dd>
                </div>
              )}
              <div className="blueprint-spec__row">
                <dt>Bus run</dt>
                <dd>
                  {sheet.bus.totalRunM.toFixed(1)} m / {sheet.bus.voltageDropPct.toFixed(1)}%
                </dd>
              </div>
              <div className="blueprint-spec__row blueprint-spec__row--wide">
                <dt>PSU driver</dt>
                <dd>{t.psu}</dd>
              </div>
            </dl>

            <div className="blueprint-actions">
              <button
                type="button"
                className="button button--primary blueprint-actions__button"
                data-testid="download-blueprint-svg"
                onClick={downloadSvg}
              >
                Download .SVG Blueprint
              </button>
              <button
                type="button"
                className="button blueprint-actions__button"
                data-testid="download-blueprint-dxf"
                onClick={downloadDxf}
              >
                Download AutoCAD .DXF
              </button>
              <p className="blueprint-actions__note mono">
                SVG: A3 sheet at {t.scale}. DXF: AutoCAD R12, model units cm, {DXF_LAYERS.length} LUMEN_* layers.
              </p>
            </div>
          </aside>

          <section className="blueprint-card blueprint-card--schedule" aria-labelledby={`${uid}-schedule`}>
            <div className="blueprint-schedule__head">
              <h3 id={`${uid}-schedule`} className="blueprint-schedule__title">
                Drilling &amp; Anchor Schedule
              </h3>
              <p className="blueprint-schedule__datum mono">X / Y from bottom-left datum at FFL</p>
            </div>
            <div className="blueprint-schedule__scroll">
              <table className="blueprint-schedule" data-testid="drilling-schedule-table">
                <thead>
                  <tr>
                    <th scope="col">Anchor</th>
                    <th scope="col">Module</th>
                    <th scope="col">SKU</th>
                    <th scope="col" className="num">
                      X (cm)
                    </th>
                    <th scope="col" className="num">
                      Y (cm)
                    </th>
                    <th scope="col">Fixing</th>
                  </tr>
                </thead>
                <tbody onMouseLeave={() => highlight(null)} onBlur={() => highlight(null)}>
                  {sheet.anchors.length === 0 ? (
                    <tr>
                      <td colSpan={6} className="blueprint-schedule__empty">
                        No modules mounted. Mount parts on the wall to issue drilling points.
                      </td>
                    </tr>
                  ) : (
                    sheet.anchors.map((a) => (
                      <tr
                        key={a.anchorId}
                        tabIndex={0}
                        data-testid="drilling-schedule-row"
                        data-anchor={a.anchorId}
                        data-x-cm={a.xCm}
                        data-y-cm={a.yCm}
                        onMouseEnter={() => highlight(a.anchorId)}
                        onFocus={() => highlight(a.anchorId)}
                      >
                        <th scope="row">{a.anchorId}</th>
                        <td>{a.moduleIndex}</td>
                        <td>{a.sku}</td>
                        <td className="num">{a.xCm.toFixed(1)}</td>
                        <td className="num">{a.yCm.toFixed(1)}</td>
                        <td>
                          {a.hardware}
                          {a.surface === 'ceiling' ? <span className="blueprint-schedule__tag">Ceiling</span> : null}
                        </td>
                      </tr>
                    ))
                  )}
                </tbody>
              </table>
            </div>
          </section>
        </div>
      </div>
    </div>
  );
}
